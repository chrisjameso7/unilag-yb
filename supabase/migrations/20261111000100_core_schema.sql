-- Public reference data
create policy "Reference data is public" on public.faculties
  for select to anon, authenticated using (true);
create policy "Reference data is public" on public.departments
  for select to anon, authenticated using (true);
create policy "Cohorts are public" on public.cohorts
  for select to anon, authenticated using (true);
create policy "Site content is public" on public.site_content
  for select to anon, authenticated using (true);

-- Published yearbook entries are public (column grants below limit what is visible)
create policy "Published profiles are public" on public.student_profiles
  for select to anon, authenticated
  using (publication_status = 'published');

-- A signed-in user can read their own private records (limited columns)
create policy "Users read their own account" on public.users
  for select to authenticated using (id = (select auth.uid()));
create policy "Users read their own verification status" on public.verification_records
  for select to authenticated using (user_id = (select auth.uid()));
create policy "Users read their own payments" on public.payments
  for select to authenticated using (user_id = (select auth.uid()));
create policy "Users read their own requests" on public.profile_edit_requests
  for select to authenticated using (user_id = (select auth.uid()));

-- Faces of the Year: only published editions, and only consented, published entries
create policy "Published editions are public" on public.faces_editions
  for select to anon, authenticated
  using (publication_status in ('published', 'archived'));

create policy "Consented entries in published editions are public" on public.faces_entries
  for select to anon, authenticated
  using (
    publication_status = 'published'
    and consent_status = 'granted'
    and exists (
      select 1 from public.faces_editions e
      where e.id = faces_entries.edition_id
        and e.publication_status in ('published', 'archived')
    )
    and exists (
      select 1 from public.student_profiles p
      where p.id = faces_entries.student_profile_id
        and p.publication_status = 'published'
    )
  );

-- admin_users, payment_events, editorial_submissions, audit_logs, rate_limits:
-- no policies => no access for anon/authenticated. Service role only.

