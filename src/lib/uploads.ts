import "server-only";
import { randomBytes } from "node:crypto";
import { adminClient } from "./supabase/admin";
import { BUCKETS } from "./supabase/storage";

export type UploadKind = "portrait" | "verification-document" | "editorial-submission";

type Rule = {
  bucket: string;
  maxBytes: number;
  types: Record<string, string>;
  label: string;
};

const IMAGE_TYPES = { "image/jpeg": "jpg", "image/png": "png", "image/webp": "webp" };

const RULES: Record<UploadKind, Rule> = {
  portrait: {
    bucket: BUCKETS.portraits,
    maxBytes: 5 * 1024 * 1024,
    types: IMAGE_TYPES,
    label: "Upload a JPEG, PNG or WebP image.",
  },
  "verification-document": {
    bucket: BUCKETS.verificationDocuments,
    maxBytes: 8 * 1024 * 1024,
    types: { ...IMAGE_TYPES, "application/pdf": "pdf" },
    label: "Upload a JPEG, PNG, WebP image or a PDF.",
  },
  "editorial-submission": {
    bucket: BUCKETS.editorialSubmissions,
    maxBytes: 15 * 1024 * 1024,
    types: IMAGE_TYPES,
    label: "Upload a JPEG, PNG or WebP image.",
  },
};

/** Identify the real file type from its first bytes; the browser's MIME type is not trusted. */
export function sniff(buffer: Buffer): string | null {
  if (buffer.length >= 3 && buffer[0] === 0xff && buffer[1] === 0xd8 && buffer[2] === 0xff) {
    return "image/jpeg";
  }
  if (
    buffer.length >= 8 &&
    buffer.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))
  ) {
    return "image/png";
  }
  if (
    buffer.length >= 12 &&
    buffer.subarray(0, 4).toString("ascii") === "RIFF" &&
    buffer.subarray(8, 12).toString("ascii") === "WEBP"
  ) {
    return "image/webp";
  }
  if (buffer.length >= 5 && buffer.subarray(0, 5).toString("ascii") === "%PDF-") {
    return "application/pdf";
  }
  return null;
}

export type SaveResult =
  | { ok: true; key: string; bucket: string; contentType: string; bytes: number }
  | { ok: false; error: string };

/**
 * Validate (size, magic bytes) and store an upload in Supabase Storage. The
 * object key is generated by us — `<owner-id>/<random>.<ext>` — and the
 * user-supplied filename is discarded. Browsers never write to Storage directly.
 */
export async function saveUpload(file: File, kind: UploadKind, ownerId: string): Promise<SaveResult> {
  const rule = RULES[kind];
  if (!file || file.size === 0) return { ok: false, error: "Choose a file to upload." };
  if (file.size > rule.maxBytes) {
    return {
      ok: false,
      error: `That file is too large. The limit is ${Math.round(rule.maxBytes / (1024 * 1024))}MB.`,
    };
  }

  const buffer = Buffer.from(await file.arrayBuffer());
  const detected = sniff(buffer);
  if (!detected || !rule.types[detected]) return { ok: false, error: rule.label };

  if (!/^[0-9a-f-]{36}$/i.test(ownerId)) return { ok: false, error: "Invalid upload owner." };
  const key = `${ownerId}/${Date.now().toString(36)}-${randomBytes(12).toString("hex")}.${rule.types[detected]}`;

  const { error } = await adminClient()
    .storage.from(rule.bucket)
    .upload(key, buffer, { contentType: detected, upsert: false, cacheControl: "31536000" });
  if (error) {
    console.error("[uploads] storage write failed", kind, error.message);
    return { ok: false, error: "The upload could not be stored. Try again in a moment." };
  }

  return { ok: true, key, bucket: rule.bucket, contentType: detected, bytes: buffer.length };
}

/** Best-effort removal of an object we no longer reference (e.g. a replaced portrait). */
export async function removeUpload(kind: UploadKind, key: string | null | undefined) {
  if (!key || key.startsWith("/") || key.startsWith("http")) return;
  const { error } = await adminClient().storage.from(RULES[kind].bucket).remove([key]);
  if (error) console.error("[uploads] remove failed", kind, error.message);
}

/** Short-lived signed URL for a private object. Callers must authorise and audit first. */
export async function signedUrl(kind: UploadKind, key: string, seconds = 120): Promise<string | null> {
  const { data, error } = await adminClient()
    .storage.from(RULES[kind].bucket)
    .createSignedUrl(key, seconds);
  if (error || !data?.signedUrl) return null;
  return data.signedUrl;
}

/** Copy a private object into the public portraits bucket (used when a Faces portrait is selected). */
export async function publishEditorialPortrait(
  submissionKey: string,
): Promise<{ ok: true; key: string } | { ok: false; error: string }> {
  const db = adminClient();
  const { data, error } = await db.storage.from(BUCKETS.editorialSubmissions).download(submissionKey);
  if (error || !data) return { ok: false, error: "The submitted portrait could not be read." };
  const buffer = Buffer.from(await data.arrayBuffer());
  const type = sniff(buffer);
  if (!type || !IMAGE_TYPES[type as keyof typeof IMAGE_TYPES]) {
    return { ok: false, error: "The submitted portrait is not a supported image." };
  }
  const ext = IMAGE_TYPES[type as keyof typeof IMAGE_TYPES];
  const key = `faces/${Date.now().toString(36)}-${randomBytes(12).toString("hex")}.${ext}`;
  const upload = await db.storage
    .from(BUCKETS.portraits)
    .upload(key, buffer, { contentType: type, upsert: false, cacheControl: "31536000" });
  if (upload.error) return { ok: false, error: "The portrait could not be published." };
  return { ok: true, key };
}
