create or replace function public.assign_public_identifier()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.public_identifier is null then
    new.public_identifier := 'ULY-' || new.graduation_year || '-'
      || lpad(nextval('public.profile_identifier_seq')::text, 5, '0');
  end if;
  return new;
end;
$$;

create trigger student_profiles_identifier
  before insert on public.student_profiles
  for each row execute function public.assign_public_identifier();

-- The permanent identity never changes once issued.
create or replace function public.protect_public_identifier()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.public_identifier is distinct from old.public_identifier then
    raise exception 'public_identifier is permanent and cannot be changed';
  end if;
  return new;
end;
$$;

create trigger student_profiles_identifier_immutable
  before update on public.student_profiles
  for each row execute function public.protect_public_identifier();

create trigger student_profiles_updated_at
  before update on public.student_profiles
  for each row execute function public.set_updated_at();

