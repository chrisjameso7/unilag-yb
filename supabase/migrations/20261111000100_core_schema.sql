-- Append-only: no role, including service_role, may edit or delete audit entries.
-- (Account deletion nulls actor_id through the FK, which is the one permitted update.)
create or replace function public.audit_logs_append_only()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'UPDATE'
     and new.actor_id is null and old.actor_id is not null
     and (new.id, new.action, new.target_type, new.target_id, new.detail, new.created_at)
         is not distinct from
         (old.id, old.action, old.target_type, old.target_id, old.detail, old.created_at) then
    return new;
  end if;
  raise exception 'audit_logs is append-only';
end;
$$;

create trigger audit_logs_no_update
  before update or delete on public.audit_logs
  for each row execute function public.audit_logs_append_only();

