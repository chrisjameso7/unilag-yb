import "server-only";
import { randomBytes } from "node:crypto";

/**
 * Studid (https://studid.io) academic verification — real API v2 integration.
 *
 * Flow (documented at https://studid.io/docs):
 *   1. POST /v2/auth/verification  { secretToken, redirectUrl, serviceName, mode }
 *      → { id, link }; redirect the student to `link`, where they sign in at their
 *        institution's SAML identity provider.
 *   2. After they return, GET /v2/auth/verification/{id} with
 *      `Authorization: Bearer <secretToken>` → { session: { entityId, affiliations,
 *        authIdentifier, authIdentifierType, test } }.
 *
 * The secretToken is generated by us per verification, kept server-side, and
 * never sent to the browser.
 *
 * UNILAG COVERAGE: Studid verifies institutions whose IdPs belong to an
 * eduGAIN-participating federation. University of Lagos is not currently listed in
 * Studid's network (Nigeria's NgRENID federation only launched in 2025), so this
 * integration stays disabled until a UNILAG entityId is confirmed. Enabling it
 * requires STUDID_ALLOWED_ENTITY_PREFIX, which pins verification to that IdP.
 *
 * We never fabricate a successful verification: when unconfigured, the product
 * offers the administrator-reviewed manual route instead.
 */

const BASE = "https://api.studid.io";

export type StudidStatus = {
  configured: boolean;
  allowedEntityPrefix: string | null;
  reason: string;
};

export function studidStatus(): StudidStatus {
  const prefix = process.env.STUDID_ALLOWED_ENTITY_PREFIX?.trim() || null;
  const explicitlyOn = process.env.STUDID_ENABLED === "true";

  if (!explicitlyOn) {
    return {
      configured: false,
      allowedEntityPrefix: prefix,
      reason:
        "Studid verification is not enabled on this deployment. UNILAG is not yet confirmed in Studid's identity-federation network, so entries are reviewed manually instead.",
    };
  }
  if (!prefix) {
    return {
      configured: false,
      allowedEntityPrefix: null,
      reason:
        "Studid is enabled but STUDID_ALLOWED_ENTITY_PREFIX is missing. Set it to the University of Lagos SAML entityId prefix so logins from other institutions cannot be accepted.",
    };
  }
  return { configured: true, allowedEntityPrefix: prefix, reason: "" };
}

export type StudidSession = {
  id: string;
  link: string;
  secretToken: string;
};

export async function createStudidVerification(redirectUrl: string): Promise<
  { ok: true; session: StudidSession } | { ok: false; error: string }
> {
  const status = studidStatus();
  if (!status.configured) return { ok: false, error: status.reason };

  const secretToken = randomBytes(32).toString("hex");

  try {
    const response = await fetch(`${BASE}/v2/auth/verification`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        secretToken,
        redirectUrl,
        serviceName: "UNILAG Yearbook",
        mode: "live",
      }),
      cache: "no-store",
    });

    const payload = (await response.json()) as {
      id?: string;
      link?: string;
      message?: string;
      error?: string;
    };

    if (!response.ok || !payload.id || !payload.link) {
      return {
        ok: false,
        error: payload.message ?? payload.error ?? "Studid could not start a verification.",
      };
    }

    return { ok: true, session: { id: payload.id, link: payload.link, secretToken } };
  } catch {
    return { ok: false, error: "Could not reach Studid. Try again in a moment." };
  }
}

export type StudidCheck =
  | { state: "pending" }
  | { state: "verified"; entityId: string; affiliations: string[]; subject: string | null }
  | { state: "rejected"; reason: string };

export async function checkStudidVerification(
  id: string,
  secretToken: string,
): Promise<StudidCheck> {
  const status = studidStatus();
  if (!status.configured) return { state: "rejected", reason: status.reason };

  try {
    const response = await fetch(`${BASE}/v2/auth/verification/${encodeURIComponent(id)}`, {
      headers: { Authorization: `Bearer ${secretToken}` },
      cache: "no-store",
    });

    if (response.status === 404) {
      return { state: "rejected", reason: "This verification has expired. Start a new one." };
    }
    if (!response.ok) {
      return { state: "pending" };
    }

    const payload = (await response.json()) as {
      session: {
        entityId: string;
        affiliations: string[];
        authIdentifier: string | null;
        authIdentifierType: string | null;
        test: boolean;
      } | null;
    };

    if (!payload.session) return { state: "pending" };

    // A test IdP session carries no academic verification and is rejected outside local dev.
    if (payload.session.test && process.env.NODE_ENV === "production") {
      return { state: "rejected", reason: "Test-mode verifications are not accepted." };
    }
    if (!payload.session.entityId.startsWith(status.allowedEntityPrefix!)) {
      return {
        state: "rejected",
        reason:
          "That login came from a different institution. Only University of Lagos identities are accepted.",
      };
    }
    if (
      payload.session.affiliations.length > 0 &&
      !payload.session.affiliations.some((a) => a === "student" || a === "member" || a === "alum")
    ) {
      return {
        state: "rejected",
        reason: "The institution did not assert a student affiliation for this login.",
      };
    }

    return {
      state: "verified",
      entityId: payload.session.entityId,
      affiliations: payload.session.affiliations,
      subject: payload.session.authIdentifier,
    };
  } catch {
    return { state: "pending" };
  }
}
