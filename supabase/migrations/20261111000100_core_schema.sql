create table public.student_profiles (
  id                   uuid primary key default gen_random_uuid(),
  user_id              uuid unique references public.users (id) on delete cascade,
  public_identifier    text not null unique, -- permanent, e.g. ULY-2026-00042 (set by trigger)
  full_name            text not null check (char_length(full_name) between 2 and 80),
  username             text not null unique
                         check (username ~ '^[a-z0-9]+(-[a-z0-9]+)*$' and char_length(username) <= 70),
  profile_image        text, -- object key in the public "portraits" bucket
  faculty_id           bigint not null,
  department_id        bigint not null,
  admission_year       integer not null check (admission_year between 1962 and 2100),
  graduation_year      integer not null check (graduation_year between 1962 and 2100),
  bio                  text not null default '' check (char_length(bio) <= 250),
  graduation_status    text not null default 'in_progress'
                         check (graduation_status in ('in_progress', 'graduated')),
  verification_status  text not null default 'unverified'
                         check (verification_status in ('unverified', 'pending', 'verified', 'rejected')),
  publication_status   text not null default 'draft'
                         check (publication_status in ('draft', 'pending_payment', 'published', 'suspended', 'removed')),
  consent_public       boolean not null default false,
  faces_opt_in         boolean not null default false,
  search_indexing      boolean not null default true,
  is_demo              boolean not null default false,
  published_at         timestamptz,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  constraint graduation_not_before_admission check (graduation_year >= admission_year),
  constraint programme_length_plausible check (graduation_year - admission_year <= 12),
  constraint owner_required_unless_demo check (is_demo or user_id is not null),
  constraint department_in_faculty
    foreign key (department_id, faculty_id) references public.departments (id, faculty_id),
  constraint faculty_fk foreign key (faculty_id) references public.faculties (id)
);

create index student_profiles_public_grad_idx
  on public.student_profiles (publication_status, graduation_year);
create index student_profiles_public_adm_idx
  on public.student_profiles (publication_status, admission_year);
create index student_profiles_department_idx on public.student_profiles (department_id);
create index student_profiles_faculty_idx on public.student_profiles (faculty_id);
