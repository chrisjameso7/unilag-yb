-- =============================================================================
-- UNILAG Yearbook — core schema (Supabase / PostgreSQL)
--
-- Plan section 10. Security model in one paragraph:
--
--   * Every table has row-level security enabled.
--   * The browser-facing roles (anon, authenticated) get NO write access to any
--     table: there are no INSERT/UPDATE/DELETE policies and the privileges are
--     revoked. All writes go through server code that has already checked the
--     user (Server Actions / route handlers using the service-role key).
--   * Reads by anon/authenticated are limited twice: by RLS (only published
--     profiles, published Faces editions, a user's own rows) and by column
--     grants (private columns such as consent flags, matriculation numbers,
--     Studid secrets, document paths and payer emails are never granted).
--   * Admin views and privileged functions are executable by service_role only.
-- =============================================================================

create extension if not exists pg_trgm with schema extensions;

